import { readFile, writeFile, mkdir, readdir, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (path) => readFile(resolve(root, path), 'utf8');
const manifest = JSON.parse(await read('.openai/hosting.json'));
if (typeof manifest.project_id !== 'string' || !manifest.project_id) {
  throw new Error('A Sites project_id is required before creating the deployment bundle.');
}

const files = [
  ['index.html', 'text/html; charset=utf-8'],
  ['app.js', 'text/javascript; charset=utf-8'],
  ['data.js', 'text/javascript; charset=utf-8'],
  ['cloud.js', 'text/javascript; charset=utf-8'],
  ['style.css', 'text/css; charset=utf-8'],
];
const artwork = (await readdir(resolve(root, 'assets'))).filter((name) => /^[a-z0-9-]+\.svg$/i.test(name)).sort();
for (const name of artwork) files.push([`assets/${name}`, 'image/svg+xml; charset=utf-8']);
const assets = await Promise.all(files.map(async ([path, type]) => [
  `/${path}`, { type, body: await read(path) },
]));

// The browser and Worker share the same strict validation rules. This tiny build
// only joins our own modules; there is no dependency resolution or code rewriting
// beyond removing their known export/import declarations.
const validation = (await read('data.js')).replace(/^export\s+(?=(?:const|function|async\s+function)\b)/gm, '');
let api = await read('server/worker.js');
const importPattern = /^import\s*\{\s*validateBackup\s*\}\s*from\s*['"]\.\.\/data\.js['"];?\s*$/m;
if (!importPattern.test(api) || !/^export default worker;?\s*$/m.test(api)) {
  throw new Error('Worker entry changed. Update the explicit module joining rules before building.');
}
api = api.replace(importPattern, '')
  .replace(/^export\s+(?=(?:const|function|async\s+function)\b)/gm, '')
  .replace(/^export default worker;?\s*$/m, '');

const bundle = `// Generated by scripts/build.mjs. Public app code only; no user data.\n${validation}\n${api}\n
const STATIC_ASSETS = new Map(${JSON.stringify(assets)});
STATIC_ASSETS.set('/', STATIC_ASSETS.get('/index.html'));
export default {
  async fetch(request, env, context) {
    const path = new URL(request.url).pathname;
    if (path.startsWith('/api/')) return worker.fetch(request, env, context);
    const asset = STATIC_ASSETS.get(path);
    if (!asset) return new Response('Not found', {
      status: 404,
      headers: { 'Content-Type': 'text/plain; charset=utf-8', 'X-Content-Type-Options': 'nosniff', 'Cache-Control': 'no-cache' },
    });
    if (request.method !== 'GET' && request.method !== 'HEAD') return new Response('Method not allowed', {
      status: 405,
      headers: { Allow: 'GET, HEAD', 'Content-Type': 'text/plain; charset=utf-8', 'X-Content-Type-Options': 'nosniff' },
    });
    return new Response(request.method === 'HEAD' ? null : asset.body, {
      headers: {
        'Content-Type': asset.type,
        'Cache-Control': 'no-cache',
        'X-Content-Type-Options': 'nosniff',
        'Referrer-Policy': 'same-origin',
      },
    });
  },
};
`;
await mkdir(resolve(root, 'dist/server'), { recursive: true });
await mkdir(resolve(root, 'dist/.openai'), { recursive: true });
await writeFile(resolve(root, 'dist/server/index.js'), bundle, 'utf8');
await copyFile(resolve(root, '.openai/hosting.json'), resolve(root, 'dist/.openai/hosting.json'));
console.log(`Built a self-contained Worker with ${assets.length} public assets (${Buffer.byteLength(bundle).toLocaleString()} bytes).`);
